
-- Swiggy SQL Case Study
-- Restaurant Performance, Customer Behavior,
-- and Delivery Partner Analytics

USE swiggydb;


-- Q1: Display all customers who live in Delhi

SELECT 
    name, city
FROM
    customers
WHERE
    city = 'Delhi';


-- Q2: Find the average rating of all restaurants in Mumbai

SELECT 
    restaurant_id, name, city, AVG(rating) AS rating
FROM
    restaurants
WHERE
    city = 'Mumbai'
GROUP BY restaurant_id , name , city;


-- Q3: List all customers who have placed at least one order

SELECT 
    customers.customer_id, customers.name, orders.order_id
FROM
    customers
        INNER JOIN
    orders USING (customer_id);


-- Q4: Display the total number of orders placed by each customer

SELECT 
    customers.customer_id,
    customers.name,
    COUNT(orders.order_id) AS total_orders
FROM
    customers
        INNER JOIN
    orders USING (customer_id)
GROUP BY customers.customer_id , customers.name;


-- Q5: Find the total revenue generated by each restaurant

SELECT 
    restaurants.name,
    restaurants.restaurant_id,
    SUM(total_amount) AS revenue
FROM
    restaurants
        JOIN
    orders USING (restaurant_id)
GROUP BY restaurants.name , restaurants.restaurant_id;


-- Q6: Find the top 5 restaurants with the highest average rating

SELECT 
    name, restaurant_id, AVG(rating) AS average_rating
FROM
    restaurants
GROUP BY name , restaurant_id
ORDER BY average_rating DESC
LIMIT 5;


-- Q7: Display all customers who have never placed an order

SELECT 
    customers.name, customers.customer_id, orders.order_id
FROM
    customers
        LEFT JOIN
    orders USING (customer_id)
WHERE
    order_id IS NULL;


-- Q8: Find the number of orders placed by each customer in Mumbai

SELECT 
    customers.name,
    customers.city,
    customers.customer_id,
    COUNT(orders.order_id)
FROM
    customers
        LEFT JOIN
    orders USING (customer_id)
WHERE
    city = 'Mumbai'
GROUP BY customers.name , customers.city , customers.customer_id;


-- Q9: Display all orders placed in the last 30 days
-- Relative to the latest order date in the dataset

SELECT 
    order_id, DATE(order_date)
FROM
    orders
WHERE
    order_date >= DATE_SUB((SELECT 
                MAX(order_date)
            FROM
                orders),
        INTERVAL 30 DAY);


-- Q10: List all delivery partners who have completed
-- more than 1 delivery

SELECT 
    deliverypartners.partner_id,
    deliverypartners.name,
    COUNT(orderdelivery.order_id) AS orders_delivered
FROM
    deliverypartners
        JOIN
    orderdelivery USING (partner_id)
GROUP BY deliverypartners.partner_id , deliverypartners.name
HAVING orders_delivered > 1;


-- Q11: Find customers who have placed orders
-- on exactly three different days

SELECT 
    customer_id, name, COUNT(DISTINCT DATE(order_date)) AS count
FROM
    orders
        JOIN
    customers USING (customer_id)
GROUP BY customer_id
HAVING count = 3;


-- Q12: Find the delivery partner who has worked
-- with the most different customers

WITH cte AS (
    SELECT
        deliverypartners.partner_id,
        deliverypartners.name,
        COUNT(DISTINCT customers.customer_id) AS count
    FROM deliverypartners
    JOIN orderdelivery USING (partner_id)
    JOIN orders USING (order_id)
    JOIN customers USING (customer_id)
    GROUP BY deliverypartners.partner_id, deliverypartners.name
    ORDER BY count DESC
)

SELECT *
FROM cte
WHERE count = (SELECT MAX(count) FROM cte);


-- Q13: Identify customers who have the same city
-- and have placed orders at the same restaurants,
-- but on different dates

WITH cte AS (
    SELECT
        customers.customer_id,
        customers.name,
        customers.city,
        restaurants.restaurant_id,
        orders.order_date
    FROM customers
    JOIN orders USING (customer_id)
    JOIN restaurants USING (restaurant_id)
)

SELECT *
FROM cte AS a
JOIN cte AS b
    ON a.city = b.city
    AND a.restaurant_id = b.restaurant_id
    AND a.order_date <> b.order_date
    AND a.customer_id < b.customer_id;
